        private const val BITCOIND_SO_NAME = "libbitcoind.so"
        private const val SIGTERM = 15

        private const val LOG_TAIL_LINES = 200
        private const val RPC_POLL_MS = 1_000L
        private const val RPC_READY_TIMEOUT_MS = 300_000L   // block index load can be slow on flash
        private const val SHUTDOWN_WAIT_MS = 60_000L        // chainstate flush
        private const val SHUTDOWN_RPC_TIMEOUT_MS = 5_000   // onDestroy joins for 8 s
        private const val ATTACHED_STOP_WAIT_MS = 30_000L
        private const val STALE_TERM_WAIT_MS = 10_000L
        private const val STATS_TIMEOUT_MS = 10_000

        /**
         * How far back to look for an unconfirmed transaction that getbalances
         * counted nowhere. Only ever reached when every balance is zero, so a
         * generous window costs nothing in the normal case.
         */
        private const val IN_FLIGHT_SCAN = 50

        /** Depth at which a coinbase becomes spendable. Consensus, not a guess. */
        private const val COINBASE_SPENDABLE_DEPTH = 101L
    }
